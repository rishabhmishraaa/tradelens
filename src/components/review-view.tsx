import type { Review } from "@/server/ai/review-schema";

/** F7: renders a validated review. `symbols` maps trade ids to symbols so ids are never shown raw. */
export function ReviewView({ review, model, symbols }: { review: Review; model: string; symbols: Record<string, string> }) {
  return (
    <article data-testid="saved-review" className="flex flex-col gap-4 rounded-lg border border-black/10 p-4 dark:border-white/15">
      <p>{review.summary}</p>

      {review.wentWell.length > 0 && (
        <div>
          <h3 className="mb-1 font-semibold">Went well</h3>
          <ul className="list-disc pl-5">
            {review.wentWell.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ul>
        </div>
      )}

      {review.mistakes.length > 0 && (
        <div>
          <h3 className="mb-1 font-semibold">Mistakes</h3>
          <ul className="flex flex-col gap-2" data-testid="review-mistakes">
            {review.mistakes.map((m) => (
              <li key={`${m.tag}-${m.tradeIds.join()}`}>
                <span className="font-medium">{m.tag}</span>{" "}
                <span className="text-sm">({m.tradeIds.map((id) => symbols[id] ?? "unknown trade").join(", ")})</span>
                <p className="text-sm">{m.insight}</p>
              </li>
            ))}
          </ul>
        </div>
      )}

      {review.patterns.length > 0 && (
        <div>
          <h3 className="mb-1 font-semibold">Patterns</h3>
          <ul className="list-disc pl-5">
            {review.patterns.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ul>
        </div>
      )}

      <p>
        <span className="font-semibold">Next session: </span>
        {review.nextSessionFocus}
      </p>
      <p className="text-xs text-neutral-700 dark:text-neutral-300">Generated by {model}. AI-written; check it against your trades.</p>
    </article>
  );
}
